// Phase 4 Feature H.2 — Indian food database seed (≥ 200 rows).
//
// Canonical reference table of common Indian foods with glycemic index
// (GI) and glycemic load (GL) for a typical Indian serving. Per
// CLAUDE.md "IndianFoodItem (seeded, 200+ rows, cited GI/GL)" and
// phase4.md §H.2, every row cites its source.
//
//   pnpm --filter @swasth/server db:seed:food-items
//
// Idempotent: upserts by the unique `nameEn`, so re-running corrects
// drifted GI/GL/source values without creating duplicates and without
// touching the foreign key from meal_logs.food_item_id (ON DELETE SET
// NULL means a reseed never destroys meal history either way).
//
// name_regional is intentionally left empty ({}) here — regional names
// are populated only as each language flag ramps (Feature J). Search
// falls back to name_en + name_hi until then (§H.1).
//
// GI/GL methodology: GI is on the glucose=100 reference scale. GL is
// computed for one typical Indian household serving as
// GL = round(GI × available_carbohydrate_g / 100). Values are drawn
// from the cited peer-reviewed tables; where an Indian-population study
// exists it is preferred over the international table.
//
// One-shot CLI script: console is the user-facing output channel.
