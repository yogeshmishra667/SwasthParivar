// Phase 4 Feature G.4 — `buildReportModel`, pure.
//
// Turns gathered health data into the PII-stripped view model the
// pre-visit PDF renders. Safety rules from CLAUDE.md G.3 are encoded here
// (not in the template) so they are unit-testable:
//   - Only the patient name + age BAND are carried — never phone,
//     household_id, or exact DoB. The input type has no slot for them.
//   - The watermark string is always present.
//   - The AI summary, when present, always carries its "for discussion
//     only" label.

import type {
  BpPoint,
  BpSummary,
  ReadingPoint,
  ReportModel,
  ReportModelInput,
  SeriesSummary,
} from "./types.js";

/** CLAUDE.md G.3 — mandatory on every report. */
export const REPORT_WATERMARK = "Generated by SwasthParivar — not a medical record" as const;

/** CLAUDE.md G.3 — the AI paragraph must be clearly labelled. */
export const REPORT_AI_SUMMARY_LABEL = "AI-generated summary, for discussion only" as const;

const round = (n: number): number => Math.round(n);

/** "67" → "60–69". Negative/odd ages are clamped to a sane band so the
 * function is total. */
export const ageToBand = (age: number): string => {
  const safe = Number.isFinite(age) && age > 0 ? Math.floor(age) : 0;
  const lower = Math.floor(safe / 10) * 10;
  return `${lower}–${lower + 9}`;
};

const summariseSeries = (points: readonly ReadingPoint[]): SeriesSummary | null => {
  if (points.length === 0) return null;
  const values = points.map((p) => p.value);
  const sum = values.reduce((a, b) => a + b, 0);
  return {
    count: values.length,
    latest: values[values.length - 1]!,
    min: Math.min(...values),
    max: Math.max(...values),
    avg: round(sum / values.length),
    values,
  };
};

const summariseBp = (points: readonly BpPoint[]): BpSummary | null => {
  if (points.length === 0) return null;
  const last = points[points.length - 1]!;
  const sysSum = points.reduce((a, b) => a + b.systolic, 0);
  const diaSum = points.reduce((a, b) => a + b.diastolic, 0);
  return {
    count: points.length,
    latestSystolic: last.systolic,
    latestDiastolic: last.diastolic,
    avgSystolic: round(sysSum / points.length),
    avgDiastolic: round(diaSum / points.length),
  };
};

export const buildReportModel = (input: ReportModelInput): ReportModel => ({
  patientName: input.name,
  ageBand: ageToBand(input.age),
  generatedAtIso: input.generatedAtIso,
  watermark: REPORT_WATERMARK,
  glucose: {
    fasting: summariseSeries(input.glucose.fasting),
    postMeal: summariseSeries(input.glucose.postMeal),
  },
  bp: summariseBp(input.bp),
  hba1cEstimate: input.hba1cEstimate,
  medAdherencePercent: input.medAdherencePercent,
  // Defensive cap at 3 — the worker passes "top 3" but the model owns
  // the invariant so the template can't accidentally render more.
  insights: input.insights.slice(0, 3),
  aiSummary:
    input.aiSummary && input.aiSummary.trim().length > 0
      ? { text: input.aiSummary.trim(), label: REPORT_AI_SUMMARY_LABEL }
      : null,
});
